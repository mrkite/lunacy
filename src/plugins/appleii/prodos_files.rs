pub fn get_prodos_type(filetype: u8, aux: u16) -> (String, String) {
    let typeaux = u32::from(filetype) | (u32::from(aux) << 8);
    for t in TYPES.iter() {
        if t.mask & typeaux == t.value {
            return (t.ext.to_string(), t.desc.to_string());
        }
    }
    (format!("${:02x}", filetype), format!("${:04x}", aux))
}
